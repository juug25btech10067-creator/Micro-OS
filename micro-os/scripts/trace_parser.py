#!/usr/bin/env python3
"""
Trace Parser for CA-6 Micro-OS.
Parses CSV trace logs generated by the Rust Micro-OS and computes
scheduling latency, turnaround time, context switches, and CPU utilization.
"""

import csv
import sys
from collections import defaultdict

def parse_trace(csv_filepath):
    events = []
    with open(csv_filepath, 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            events.append({
                'tick': int(row['tick']),
                'event_type': row['event_type'],
                'task_id': row['task_id'],
                'details': row['details']
            })
    return events

def analyze_trace(events):
    if not events:
        print("[!] No events found in trace.")
        return

    task_spawns = {}
    task_terminations = {}
    task_dispatches = defaultdict(int)
    task_preemptions = defaultdict(int)
    total_ticks = max(e['tick'] for e in events) if events else 0

    for ev in events:
        tid = ev['task_id']
        etype = ev['event_type']
        tick = ev['tick']

        if etype == 'TASK_SPAWN':
            task_spawns[tid] = tick
        elif etype == 'TASK_TERMINATED':
            task_terminations[tid] = tick
        elif etype == 'DISPATCH':
            task_dispatches[tid] += 1
        elif etype == 'PREEMPT':
            task_preemptions[tid] += 1

    print("=" * 65)
    print("           CA-6 SCHEDULER TRACE ANALYSIS REPORT")
    print("=" * 65)
    print(f"Total Ticks Recorded    : {total_ticks}")
    print(f"Total Events Logged     : {len(events)}")
    print(f"Unique Tasks Observed   : {len(task_spawns)}")
    print("-" * 65)
    print(f"{'Task ID':<10} {'Arrival':<10} {'Finish':<10} {'Turnaround':<12} {'Dispatches':<12}")
    print("-" * 65)

    turnarounds = []
    for tid, arr in task_spawns.items():
        fin = task_terminations.get(tid, total_ticks)
        tat = fin - arr
        turnarounds.append(tat)
        disp = task_dispatches.get(tid, 0)
        print(f"{tid:<10} {arr:<10} {fin:<10} {tat:<12} {disp:<12}")

    if turnarounds:
        avg_tat = sum(turnarounds) / len(turnarounds)
        print("-" * 65)
        print(f"Average Turnaround Time : {avg_tat:.2f} ticks")
        print(f"Maximum Turnaround Time : {max(turnarounds)} ticks")
    print("=" * 65)

if __name__ == '__main__':
    path = sys.argv[1] if len(sys.argv) > 1 else 'traces/demo1_rr_trace.csv'
    try:
        events = parse_trace(path)
        analyze_trace(events)
    except FileNotFoundError:
        print(f"Trace file not found: {path}. Run the Rust binary first to generate traces.")
